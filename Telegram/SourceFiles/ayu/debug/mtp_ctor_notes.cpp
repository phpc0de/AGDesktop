const CtorNote *FindCtorNote(const char *name) {
	for (const auto &note : kCtorNotes) {
		if (std::strcmp(note.name, name) == 0) {
			return &note;
		}
	}
	return nullptr;
}

const FieldNote *FindFieldNote(const char *name) {
	for (const auto &note : kFieldNotes) {
		if (std::strcmp(note.name, name) == 0) {
			return &note;
		}
	}
	return nullptr;
}

