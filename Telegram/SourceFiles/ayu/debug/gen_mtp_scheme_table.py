#!/usr/bin/env python3
# Generates mtp_scheme_table.h from the repo's TL schemes.
# Run from repo root: python3 Telegram/SourceFiles/ayu/debug/gen_mtp_scheme_table.py
import re
import sys
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
for _ in range(6):
    if os.path.isfile(os.path.join(
            ROOT, 'Telegram/SourceFiles/mtproto/scheme/api.tl')):
        break
    ROOT = os.path.dirname(ROOT)
SCHEMES = [
    os.path.join(ROOT, 'Telegram/SourceFiles/mtproto/scheme/mtproto.tl'),
    os.path.join(ROOT, 'Telegram/SourceFiles/mtproto/scheme/api.tl'),
]
OUT = os.path.join(ROOT, 'Telegram/SourceFiles/ayu/debug/mtp_scheme_table.h')

ctor_re = re.compile(
    r'^([a-zA-Z_][\w.]*)#([0-9a-fA-F]{1,8})\s+(.*?)\s*=\s*([\w.]+(?:<[^;]+>)?);$')
field_re = re.compile(r'^([\w#]+):(.+)$')
# flags2+ groups exist (user#..., channel#...): encode their bit as
# (group << 8) | N so decoders can address the right "#" field.
opt_re = re.compile(r'^(flags\d*)\.(\d+)\?(.+)$')

ctors = {}
order = []
for path in SCHEMES:
    for raw in open(path, encoding='utf-8'):
        line = raw.strip()
        if not line or line.startswith('//'):
            continue
        m = ctor_re.match(line)
        if not m:
            continue
        name, cid, fields_s, parent = m.groups()
        key = int(cid, 16)
        if key in ctors:
            continue
        fields = []
        if fields_s.strip():
            for f in fields_s.split(' '):
                fm = field_re.match(f)
                if not fm:
                    fields.append((f, 'X', 0xFFFF))
                    continue
                fname, ftype = fm.group(1), fm.group(2)
                bit = 0xFFFF
                om = opt_re.match(ftype)
                if om:
                    grp = om.group(1)
                    grpnum = int(grp[5:]) if len(grp) > 5 else 0
                    bit = (grpnum << 8) | int(om.group(2))
                    ftype = om.group(3)
                ftype = ftype.replace('%', '')
                fields.append((fname, ftype, bit))
        ctors[key] = (name, parent, fields)
        order.append(key)


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


lines = []
lines.append('// Generated by gen_mtp_scheme_table.py from api.tl + mtproto.tl — do not edit.')
lines.append('#pragma once')
lines.append('')
lines.append('#include <cstdint>')
lines.append('')
lines.append('namespace Ayu::Debug::Scheme {')
lines.append('')
lines.append('struct FieldDesc {')
lines.append('\tconst char *name;')
lines.append('\tconst char *type;')
lines.append('\tuint16_t flagBit; // 0xFFFF = required')
lines.append('};')
lines.append('')
lines.append('struct CtorDesc {')
lines.append('\tuint32_t id;')
lines.append('\tconst char *name;')
lines.append('\tconst char *parent;')
lines.append('\tuint16_t fieldsCount;')
lines.append('\tconst FieldDesc *fields;')
lines.append('};')
lines.append('')
for idx, key in enumerate(order):
    name, parent, fields = ctors[key]
    if not fields:
        continue
    lines.append('inline constexpr FieldDesc kFields%d[] = {' % idx)
    for (fname, ftype, bit) in fields:
        lines.append('\t{%s, %s, %d},' % (cstr(fname), cstr(ftype), bit))
    lines.append('};')
    lines.append('')
lines.append('inline constexpr CtorDesc kCtors[] = {')
rows = 0
for idx, key in enumerate(order):
    name, parent, fields = ctors[key]
    fp = 'kFields%d' % idx if fields else 'nullptr'
    fc = len(fields) if fields else 0
    lines.append('\t{0x%08xu, %s, %s, %du, %s},'
                 % (key, cstr(name), cstr(parent), fc, fp))
    rows += 1
lines.append('};')
lines.append('')
lines.append('inline constexpr int kCtorsCount = %d;' % len(order))
lines.append('')
lines.append('} // namespace Ayu::Debug::Scheme')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
sys.stderr.write('ctors: %d parsed, %d rows written\n' % (len(ctors), rows))
if rows != len(ctors):
    sys.stderr.write('WARNING: %d parsed ctors missing from the table\n'
                     % (len(ctors) - rows))
print('wrote %s (%d ctors)' % (OUT, len(order)))
